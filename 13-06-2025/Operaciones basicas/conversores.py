print("Conversión de Tipos de Datos")

numero = 90

texto_numero = str(numero)

lista_texto = list("Hola")

numero_flotante = float("3.14")      

print(f"str(90) → {texto_numero} (tipo: {type(texto_numero)})")
print(f'list("Hola") → {lista_texto} (tipo: {type(lista_texto)})')
print(f'float("3.14") → {numero_flotante} (tipo: {type(numero_flotante)})')