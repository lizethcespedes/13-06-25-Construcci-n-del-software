print(" Operaciones Lógicas")

a = True
b = False

# Operaciones lógicas
and_logico = a and b       # True Y False → False
or_logico = a or b         # True O False → True
not_logico = not a         # No True → False

print(f"a = {a}")
print(f"b = {b}\n")

print("Resultados lógicos:")
print(f"a AND b  ➤ {and_logico}")
print(f"a OR b   ➤ {or_logico}")
print(f"NOT a    ➤ {not_logico}")
